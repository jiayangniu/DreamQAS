"""T1.a — counterfactual action-ranking probe (the QAS-specific RQ3(a) evidence).

Question: for a real circuit prefix s_t, can the WM RANK the legal next actions by the post-VQE
quality of the resulting continuation? (This is closer to the QAS contribution than generic
pairwise fidelity.) Also: does multi-step endpoint ranking hold as the imagined horizon grows?

Protocol (locked plan §5 T1.a):
  - Prefixes: held-out, generated by the FROZEN actor rolled to early/mid/late depth (policy-visited,
    independent of WM training, NOT from DAgger logs). P prefixes per depth bucket.
  - Candidates: up to M legal next actions at the prefix.
  - WM score: pred_logerr of each continuation prefix+[a] (batched via _encode_seeds; no VQE).
  - Ground truth: real error of prefix+[a] via _vqe_circuit (TRAINING-IDENTICAL VQE).
  - Per-prefix metrics: Spearman(pred, log10 real); top-k recall; normalized selected-action regret;
    actor-chosen-action percentile; WM-top-1 vs matched-random (multiple randoms, paired).
  - Aggregate: per-prefix rho -> rho_action = mean, bootstrap CI (NOT pooled across prefixes).
  - Horizon: endpoint ranking fidelity for H in {1,5,10,15} (pred vs real endpoint log-error).

Usage: python analysis/t1a_action_ranking.py <run_dir> [--device cpu|cuda:0] [--P 5] [--M 10]
       [--ckpts final|onset,final] [--horizons 1,5,10,15] [--tag t1a]
Writes <run_dir>/t1a_probe.json.
"""
